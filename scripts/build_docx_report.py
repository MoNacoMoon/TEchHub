# -*- coding: utf-8 -*-
import os
import sys
from docx import Document
from docx.shared import Pt, Cm, Inches, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_ALIGN_VERTICAL
from docx.oxml import OxmlElement, parse_xml
from docx.oxml.ns import nsdecls, qn

def create_report():
    doc = Document()

    # 1. Настройка полей страницы по ГОСТ (Левое: 30 мм, Правое: 15 мм, Верхнее: 20 мм, Нижнее: 20 мм)
    for section in doc.sections:
        section.top_margin = Cm(2.0)
        section.bottom_margin = Cm(2.0)
        section.left_margin = Cm(3.0)
        section.right_margin = Cm(1.5)
        section.page_width = Cm(21.0)
        section.page_height = Cm(29.7)

    # 2. Настройка базового стиля текста по ГОСТ: Times New Roman, 12 pt, 1.5 интервал, абзацный отступ 1.25 см
    style_normal = doc.styles['Normal']
    font = style_normal.font
    font.name = 'Times New Roman'
    font.size = Pt(12)
    font.color.rgb = RGBColor(0, 0, 0)
    style_normal.paragraph_format.line_spacing = 1.5
    style_normal.paragraph_format.space_after = Pt(0)
    style_normal.paragraph_format.space_before = Pt(0)
    style_normal.paragraph_format.first_line_indent = Cm(1.25)
    style_normal.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

    # Вспомогательные функции добавления элементов
    def add_p(text, bold_prefix=None, indent=True, align=WD_ALIGN_PARAGRAPH.JUSTIFY):
        p = doc.add_paragraph()
        p.alignment = align
        p.paragraph_format.first_line_indent = Cm(1.25) if indent else Cm(0)
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.space_before = Pt(0)
        if bold_prefix:
            run_b = p.add_run(bold_prefix)
            run_b.font.name = 'Times New Roman'
            run_b.font.size = Pt(12)
            run_b.font.bold = True
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(12)
        return p

    def add_h1(text):
        p = doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.space_before = Pt(14)
        p.paragraph_format.space_after = Pt(6)
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.keep_with_next = True
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(14)
        run.font.bold = True
        return p

    def add_h2(text):
        p = doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.space_before = Pt(10)
        p.paragraph_format.space_after = Pt(4)
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.keep_with_next = True
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(13)
        run.font.bold = True
        return p

    def add_h3(text):
        p = doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.space_before = Pt(8)
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.keep_with_next = True
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(12)
        run.font.bold = True
        return p

    def add_bullet_item(text, bold_prefix=None):
        p = doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(1.25)
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.space_before = Pt(0)
        run_dot = p.add_run("— ")
        run_dot.font.name = 'Times New Roman'
        run_dot.font.size = Pt(12)
        if bold_prefix:
            run_b = p.add_run(bold_prefix)
            run_b.font.name = 'Times New Roman'
            run_b.font.size = Pt(12)
            run_b.font.bold = True
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(12)
        return p

    def add_table_data(headers, rows, caption=None):
        if caption:
            cp = doc.add_paragraph()
            cp.alignment = WD_ALIGN_PARAGRAPH.LEFT
            cp.paragraph_format.first_line_indent = Cm(0)
            cp.paragraph_format.space_before = Pt(6)
            cp.paragraph_format.space_after = Pt(2)
            run_c = cp.add_run(caption)
            run_c.font.name = 'Times New Roman'
            run_c.font.size = Pt(12)

        table = doc.add_table(rows=len(rows) + 1, cols=len(headers))
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.autofit = True

        # Стили границ таблицы
        tblPr = table._tbl.tblPr
        borders = parse_xml(
            r'<w:tblBorders %s>'
            r'  <w:top w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'  <w:bottom w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'  <w:insideH w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'  <w:insideV w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'  <w:left w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'  <w:right w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'</w:tblBorders>' % nsdecls('w')
        )
        tblPr.append(borders)

        # Заголовки
        hdr_cells = table.rows[0].cells
        for idx, header_text in enumerate(headers):
            cell = hdr_cells[idx]
            cell.text = header_text
            shading = parse_xml(r'<w:shd %s w:fill="F1F5F9"/>' % nsdecls('w'))
            cell._tc.get_or_add_tcPr().append(shading)
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.line_spacing = 1.0
            p.runs[0].font.name = 'Times New Roman'
            p.runs[0].font.size = Pt(11)
            p.runs[0].font.bold = True

        # Данные
        for r_idx, row_data in enumerate(rows):
            row_cells = table.rows[r_idx + 1].cells
            for c_idx, cell_value in enumerate(row_data):
                cell = row_cells[c_idx]
                cell.text = str(cell_value)
                p = cell.paragraphs[0]
                p.paragraph_format.first_line_indent = Cm(0)
                p.paragraph_format.line_spacing = 1.15
                p.runs[0].font.name = 'Times New Roman'
                p.runs[0].font.size = Pt(11)

        # Отступ после таблицы
        post_p = doc.add_paragraph()
        post_p.paragraph_format.space_before = Pt(4)
        post_p.paragraph_format.space_after = Pt(4)
        post_p.paragraph_format.line_spacing = 1.0

    def add_code(code_text):
        p = doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.line_spacing = 1.0
        p.paragraph_format.space_before = Pt(4)
        p.paragraph_format.space_after = Pt(6)
        
        # Добавляем рамку и серый фон через XML
        tcPr = parse_xml(
            r'<w:pBdr %s>'
            r'  <w:top w:val="single" w:sz="4" w:space="4" w:color="CBD5E1"/>'
            r'  <w:left w:val="single" w:sz="18" w:space="8" w:color="4338CA"/>'
            r'  <w:bottom w:val="single" w:sz="4" w:space="4" w:color="CBD5E1"/>'
            r'  <w:right w:val="single" w:sz="4" w:space="4" w:color="CBD5E1"/>'
            r'</w:pBdr>' % nsdecls('w')
        )
        p._p.get_or_add_pPr().append(tcPr)
        shd = parse_xml(r'<w:shd %s w:fill="F8FAFC"/>' % nsdecls('w'))
        p._p.get_or_add_pPr().append(shd)

        run = p.add_run(code_text)
        run.font.name = 'Consolas'
        run.font.size = Pt(9.5)

    # =========================================================================
    # ТИТУЛЬНЫЙ ЛИСТ
    # =========================================================================
    p_header = doc.add_paragraph()
    p_header.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_header.paragraph_format.first_line_indent = Cm(0)
    p_header.paragraph_format.line_spacing = 1.15
    run = p_header.add_run("МИНИСТЕРСТВО ПРОСВЕЩЕНИЯ РОССИЙСКОЙ ФЕДЕРАЦИИ\n"
                          "ГПОУ «КОЛЛЕДЖ ИНФОРМАЦИОННЫХ ТЕХНОЛОГИЙ И ПРОГРАММИРОВАНИЯ»\n"
                          "Отделение информационных систем и программирования\n\n")
    run.font.name = 'Times New Roman'
    run.font.size = Pt(11)
    run.font.bold = True

    p_spacer = doc.add_paragraph()
    p_spacer.paragraph_format.space_before = Pt(40)

    p_title = doc.add_paragraph()
    p_title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_title.paragraph_format.first_line_indent = Cm(0)
    p_title.paragraph_format.line_spacing = 1.3
    run = p_title.add_run("ОТЧЕТ\n"
                          "ПО ИНДИВИДУАЛЬНОМУ ПРАКТИЧЕСКОМУ ЗАДАНИЮ\n\n"
                          "Тема: «Разработка и внедрение информационного ресурса\n"
                          "«Электронный учебный кабинет преподавателя и студента»»\n")
    run.font.name = 'Times New Roman'
    run.font.size = Pt(14)
    run.font.bold = True

    p_meta = doc.add_paragraph()
    p_meta.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_meta.paragraph_format.first_line_indent = Cm(0)
    p_meta.paragraph_format.line_spacing = 1.15
    run = p_meta.add_run("по профессиональному модулю ПМ.03\n"
                         "«Внедрение и поддержка компьютерных систем»\n"
                         "Специальность 09.02.07 «Информационные системы и программирование»\n")
    run.font.name = 'Times New Roman'
    run.font.size = Pt(12)

    p_spacer2 = doc.add_paragraph()
    p_spacer2.paragraph_format.space_before = Pt(50)

    p_author = doc.add_paragraph()
    p_author.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p_author.paragraph_format.first_line_indent = Cm(0)
    p_author.paragraph_format.line_spacing = 1.15
    run = p_author.add_run("Выполнил: студент гр. ИС-41\n"
                          "Иванов И. И. ____________________\n\n"
                          "Проверил: преподаватель спецдисциплин\n"
                          "Смирнов А. П. ____________________\n"
                          "Оценка: __________________________\n"
                          "Дата: «___» _____________ 2026 г.\n")
    run.font.name = 'Times New Roman'
    run.font.size = Pt(12)

    p_spacer3 = doc.add_paragraph()
    p_spacer3.paragraph_format.space_before = Pt(60)

    p_city = doc.add_paragraph()
    p_city.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_city.paragraph_format.first_line_indent = Cm(0)
    p_city.paragraph_format.line_spacing = 1.0
    run = p_city.add_run("2026 г.")
    run.font.name = 'Times New Roman'
    run.font.size = Pt(12)

    doc.add_page_break()

    # =========================================================================
    # СОДЕРЖАНИЕ
    # =========================================================================
    add_h1("СОДЕРЖАНИЕ")
    toc_items = [
        ("ВВЕДЕНИЕ. ЦЕЛЬ И ПОСТАНОВКА ЗАДАЧИ", "3"),
        ("1. ТЕХНИЧЕСКОЕ ЗАДАНИЕ НА РАЗРАБОТКУ", "4"),
        ("   1.1. Ролевая модель и разграничение прав доступа", "4"),
        ("   1.2. Требования к контрольным вопросам и тестированию", "5"),
        ("2. ОПИСАНИЕ АРХИТЕКТУРЫ И СТЕКА ТЕХНОЛОГИЙ", "6"),
        ("   2.1. Обоснование стека C# / ASP.NET Core Web API + MVC", "6"),
        ("   2.2. Сервер баз данных и ORM Entity Framework Core", "7"),
        ("3. ПРОЕКТИРОВАНИЕ БАЗЫ ДАННЫХ", "8"),
        ("   3.1. Спецификация сущностей и связей реляционной модели", "8"),
        ("   3.2. Схема связей данных (ER-диаграмма)", "10"),
        ("4. ОПИСАНИЕ РЕАЛИЗОВАННЫХ ФУНКЦИЙ СИСТЕМЫ", "11"),
        ("   4.1. Серверный алгоритм последовательного открытия лекций", "11"),
        ("   4.2. Автоматическая проверка 6 типов контрольных вопросов", "12"),
        ("   4.3. Модуль тестирования с таймером и рандомизацией", "14"),
        ("   4.4. Панель преподавателя, аналитическая матрица и аудит", "15"),
        ("5. СПЕЦИФИКАЦИЯ REST WEB API И ИНТЕГРАЦИЯ SWAGGER", "16"),
        ("6. ДИЗАЙН И ПОЛЬЗОВАТЕЛЬСКИЙ ИНТЕРФЕЙС", "18"),
        ("7. ПРИМЕРЫ УЧЕБНЫХ ДИСЦИПЛИН И КОНТРОЛЬНЫХ МАТЕРИАЛОВ", "20"),
        ("8. ПРОВЕРКА ПОСЛЕДОВАТЕЛЬНОГО ОТКРЫТИЯ ЛЕКЦИЙ", "22"),
        ("9. ВНЕДРЕНИЕ НА КОМПЬЮТЕР ПРЕПОДАВАТЕЛЯ И СЕТЕВОЙ ДОСТУП", "23"),
        ("10. ПЛАН И РЕЗУЛЬТАТЫ КОМПЛЕКСНОГО ТЕСТИРОВАНИЯ", "25"),
        ("11. РУКОВОДСТВО ПОЛЬЗОВАТЕЛЯ", "27"),
        ("    11.1. Инструкция для преподавателя", "27"),
        ("    11.2. Инструкция для студента", "29"),
        ("12. РЕГЛАМЕНТ СОПРОВОЖДЕНИЯ И РЕЗЕРВНОГО КОПИРОВАНИЯ", "30"),
        ("ЗАКЛЮЧЕНИЕ", "32"),
        ("СПИСОК ИСПОЛЬЗОВАННЫХ ИСТОЧНИКОВ", "33")
    ]
    for item, page in toc_items:
        p = doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.line_spacing = 1.15
        p.paragraph_format.space_after = Pt(2)
        dots = ". " * int((60 - len(item)))
        run = p.add_run(f"{item} {dots} {page}")
        run.font.name = 'Times New Roman'
        run.font.size = Pt(11)

    doc.add_page_break()

    # =========================================================================
    # ВВЕДЕНИЕ. ЦЕЛЬ И ПОСТАНОВКА ЗАДАЧИ
    # =========================================================================
    add_h1("ВВЕДЕНИЕ. ЦЕЛЬ И ПОСТАНОВКА ЗАДАЧИ")

    add_p(
        "В современных образовательных учреждениях среднего профессионального и высшего образования ключевую роль "
        "играют цифровые инструменты дистанционного и смешанного обучения. Организация самостоятельной работы "
        "студентов требует не просто предоставления доступа к электронным файлам, но и внедрения строгого "
        "педагогического контроля усвоения знаний, обеспечивающего систематичность и последовательность учебного процесса."
    )
    add_p(
        "Целью настоящей индивидуальной практической работы является проектирование, разработка и практическое "
        "внедрение на рабочем месте преподавателя сетевого программного ресурса «Электронный учебный кабинет преподавателя "
        "и студента», гарантирующего последовательное открытие учебных тем и лекций строго по мере успешного "
        "выполнения студентами контрольных заданий и сдачи тестов."
    )
    add_p(
        "Для достижения поставленной цели необходимо решить следующие задачи:", bold_prefix="Задачи работы: "
    )
    add_bullet_item("Спроектировать и реализовать архитектуру гибридного веб-приложения на платформе ASP.NET Core (Web API + MVC) с использованием языка программирования C#;");
    add_bullet_item("Разработать реляционную базу данных в среде SQLite с применением ORM Entity Framework Core, поддерживающую иерархическую структуру «Дисциплина → Тема → Лекция» и хранение индивидуального прогресса;");
    add_bullet_item("Реализовать и строго верифицировать серверный алгоритм последовательного открытия лекций, исключающий возможность обхода учебной программы прямым обращением к URL-адресам;");
    add_bullet_item("Создать модуль интерактивных контрольных вопросов с автоматической проверкой 6 типов заданий и возможностью экспертного рецензирования развернутых ответов преподавателем;");
    add_bullet_item("Разработать подсистему тестирования с настраиваемым лимитом попыток, проходным баллом, таймером ограничения времени и перемешиванием вариантов;");
    add_bullet_item("Создать современный адаптивный интерфейс на базе CSS-дизайн-системы с цветовой индикацией статусов обучения;");
    add_bullet_item("Интегрировать спецификацию OpenAPI и интерфейс Swagger UI для тестирования программных точек входа REST API;");
    add_bullet_item("Выполнить развертывание приложения на компьютере преподавателя, настроить брандмауэр для доступа студентов по локальной сети аудитории, составить регламент резервного копирования и пользовательские инструкции.");

    # =========================================================================
    # 1. ТЕХНИЧЕСКОЕ ЗАДАНИЕ
    # =========================================================================
    add_h1("1. ТЕХНИЧЕСКОЕ ЗАДАНИЕ НА РАЗРАБОТКУ")

    add_h2("1.1. Ролевая модель и разграничение прав доступа")
    add_p(
        "В соответствии с требованиями технического задания система обеспечивает разграничение прав доступа для "
        "трех категорий пользователей: преподавателя, студента и системного администратора. Для защиты персональных данных "
        "пароли пользователей хранятся в базе данных исключительно в виде криптографических хешей PBKDF2 с уникальной "
        "солью, формируемых стандартным компонентом ASP.NET Core Identity PasswordHasher."
    )

    tbl_roles_hdr = ["Функциональная возможность", "Преподаватель", "Студент"]
    tbl_roles_rows = [
        ["Добавление, редактирование и удаление дисциплин", "Да", "Нет"],
        ["Формирование структуры тем и лекций", "Да", "Нет"],
        ["Загрузка конспектов лекций (PDF, DOCX)", "Да", "Нет"],
        ["Создание контрольных вопросов (6 типов)", "Да", "Нет"],
        ["Формирование тестов и критериев сдачи", "Да", "Нет"],
        ["Изучение теоретического материала", "Да", "Да (доступных)"],
        ["Выполнение контрольных вопросов", "Да (проверка)", "Да"],
        ["Прохождение тестирования", "Да (проверка)", "Да"],
        ["Просмотр результатов тестирования", "Да (всей группы)", "Только своих"],
        ["Сводная матрица успеваемости группы", "Да", "Нет"],
        ["Индивидуальное ручное открытие лекций", "Да (с аудитом)", "Нет"],
        ["Сброс попыток сдачи тестов", "Да (с аудитом)", "Нет"],
        ["Резервное копирование и восстановление базы", "Да", "Нет"]
    ]
    add_table_data(tbl_roles_hdr, tbl_roles_rows, "Таблица 1.1 — Матрица разграничения прав доступа")

    add_h2("1.2. Требования к контрольным вопросам и тестированию")
    add_p(
        "Система обеспечивает поддержку 6 типов контрольных вопросов: с выбором одного верного ответа (SingleChoice), "
        "с множественным выбором (MultipleChoice), с вводом краткого ответа (ShortText), с подстановкой пропущенного термина "
        "(FillBlank), на установление соответствия пар (Matching) и развернутого ответа (OpenEnded)."
    )
    add_p(
        "Модуль тестирования настраивается преподавателем индивидуально к каждой лекции со следующими параметрами: "
        "проходной балл (по умолчанию 70%), максимальное число попыток (по умолчанию 3), ограничение времени в минутах "
        "с обратным отсчетом на клиенте и автоматической фиксацией результатов."
    )

    # =========================================================================
